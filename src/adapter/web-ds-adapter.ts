import { fileURLToPath } from 'node:url'

import { DsReadBridge } from '../bridge/ds-read-bridge.js'
import { ClickSender } from '../bridge/click-sender.js'
import { IncrementalSender } from './incremental-sender.js'
import { ToolPromptBuilder } from './tool-prompt-builder.js'
import { requestSendApproval } from '../approval/dsh-approval.js'
import {
  getWorkspaceKey,
  getWorkspaceState,
  updateWorkspaceState,
} from './workspace-state.js'

type ToolCallId = string

interface Context {
  get(name: string): unknown
  effect(fn: () => () => void): void
  [key: string]: unknown
}

interface GenerateOptions {
  provider: string
  model: string
  messages: any[]
  system?: string
  tools?: Array<{
    name: string
    description: string
    parameters: Record<string, unknown>
  }>
  temperature?: number
  maxTokens?: number
  signal?: AbortSignal
  sessionId?: string
  purpose?: string
  [key: string]: unknown
}

interface StreamChunk {
  type: string
  [key: string]: unknown
}

interface Config {
  dsReadScript: string
  sendScript: string
  pythonCommand?: string
  pollIntervalMs?: number
  replyTimeoutMs?: number
  stableReadsRequired?: number
  approvalEnabled?: boolean
  approvalHeading?: string
  approvalPreviewChars?: number
  failClosedWithoutApproval?: boolean
}

interface ParsedToolCall {
  id: ToolCallId
  name: string
  arguments: string
}

interface ParsedReply {
  text: string
  toolCalls: ParsedToolCall[]
}

/**
 * 匹配 markdown fenced code block。
 * 接受 tool_call / tool-calls / json / ds-agent 四种 fence tag。
 */
const FENCED_BLOCK_RE =
  /```(tool_call|tool-calls|json|ds-agent)[ \t]*\r?\n([\s\S]*?)\r?\n```/g

const INTERNAL_MARKERS = [
  'Current runtime context. This snapshot supersedes',
  '<system-reminder>',
  'A skill is a reusable set of task-specific instructions',
  'Generate the session title from this JSON array',
  'Generate a concise title',
  '<available_skills>',
]

function isInternalText(text: string): boolean {
  if (!text) return false
  for (const marker of INTERNAL_MARKERS) {
    if (text.includes(marker)) return true
  }
  return false
}

export class WebDsAdapter {
  private bridge: DsReadBridge
  private sender: ClickSender
  private incremental = new IncrementalSender()
  private toolPrompt = new ToolPromptBuilder()

  constructor(private ctx: Context, private config: Config) {
    const python = config.pythonCommand?.trim() || 'python'
    this.bridge = new DsReadBridge(config.dsReadScript, python)
    const pluginRoot = fileURLToPath(new URL('../../', import.meta.url))
    this.sender = new ClickSender(pluginRoot, config.sendScript, python)
  }

  providerInfo(provider: string) {
    return { id: provider, name: 'DeepSeek Web (web-ds)' }
  }

  providerRetryPolicy() {
    return undefined
  }

  imageRequestPricing() {
    return undefined
  }

  async listModels(provider: string) {
    return [{ provider, id: 'web-ds', name: 'web-ds' }]
  }

  async resolveModel(provider: string, model: string) {
    return {
      provider,
      id: model,
      name: model,
      description:
        'Answers generated by the DeepSeek web UI through a local keyboard-automation bridge.',
      inputModalities: ['text'],
      context: { contextWindow: 64000 },
      defaultMaxTokens: 8192,
      systemPromptUpdate: 'in-history',
    }
  }

  async prepareCall(provider: string, model: string, _signal?: AbortSignal) {
    const resolved = await this.resolveModel(provider, model)
    return {
      model: resolved,
      stream: (options: GenerateOptions) => this.stream(options),
    }
  }

  async *stream(options: GenerateOptions): AsyncIterable<StreamChunk> {
    const signal = options.signal
    signal?.throwIfAborted()

    // 辅助调用：本地处理，不发网页版
    if (options.purpose === 'session-title') {
      const title = this.deriveTitle(options.messages)
      yield { type: 'block-start', index: 0, blockType: 'text' }
      yield { type: 'text-delta', index: 0, text: title }
      yield {
        type: 'block-end',
        index: 0,
        block: { type: 'text', text: title },
      }
      yield {
        type: 'usage',
        usage: {
          inputTokens: 0,
          outputTokens: Math.ceil(title.length / 4),
        },
      }
      yield { type: 'finish', reason: { kind: 'stop' } }
      return
    }

    if (options.purpose === 'compaction') {
      yield { type: 'finish', reason: { kind: 'stop' } }
      return
    }

    const wsKey = getWorkspaceKey(options)
    const wsState = getWorkspaceState(wsKey)
    const isFirstTurn = !wsState.sessionId

    console.log(
      '[web-ds] stream 开始 key=' +
        wsKey +
        ' isFirstTurn=' +
        isFirstTurn +
        ' sessionId=' +
        wsState.sessionId,
    )

    const baseText = this.incremental.build(
      options.messages,
      wsState.lastMessageId,
      wsState.sentCount,
      isFirstTurn,
    )

    if (!baseText) {
      console.log('[web-ds] 无新增消息，跳过发送')
      yield { type: 'finish', reason: { kind: 'stop' } }
      return
    }

    // 协议在前，用户消息在中，工具清单在后
    const prefix = this.toolPrompt.buildPrefix(options.tools)
    const suffix = this.toolPrompt.buildSuffix(options.tools)

    const textParts: string[] = []
    if (prefix) textParts.push(prefix)
    textParts.push(baseText)
    if (suffix) textParts.push(suffix)
    const text = textParts.join('\n\n')

    // 审批
    let approved = true
    if (this.config.approvalEnabled !== false) {
      approved = await requestSendApproval(
        this.ctx,
        baseText,
        options.sessionId ? String(options.sessionId) : undefined,
        {
          heading:
            this.config.approvalHeading ??
            'About to send this message to the DeepSeek web UI:',
          previewChars: this.config.approvalPreviewChars ?? 2000,
          failClosedWithoutApproval:
            this.config.failClosedWithoutApproval ?? true,
        },
      )
    }
    if (!approved) {
      yield {
        type: 'finish',
        reason: {
          kind: 'aborted',
          failure: { message: '用户拒绝发送', code: 'APPROVAL_REJECTED' },
        },
      }
      return
    }

    try {
      await this.sender.send(text, isFirstTurn)
    } catch (err) {
      const e = err as any
      const detail = [
        e?.message ? String(e.message) : '',
        e?.stderr ? 'STDERR: ' + String(e.stderr).slice(0, 2000) : '',
        e?.stdout ? 'STDOUT: ' + String(e.stdout).slice(0, 2000) : '',
      ]
        .filter(Boolean)
        .join('\n')
      yield {
        type: 'finish',
        reason: {
          kind: 'error',
          failure: { message: '发送失败：\n' + detail, code: 'SEND_FAILED' },
        },
      }
      return
    }

    let sessionId = wsState.sessionId
    if (!sessionId) {
      console.log('[web-ds] 首次发送，等待新会话建立...')
      await new Promise((r) => setTimeout(r, 5000))
      sessionId = await this.bridge.detectSessionId()
      if (sessionId) {
        console.log('[web-ds] 新会话 id =', sessionId)
        updateWorkspaceState(wsKey, { sessionId })
      }
    } else {
      console.log('[web-ds] 复用现有会话 id =', sessionId)
    }

    if (!sessionId) {
      yield {
        type: 'finish',
        reason: {
          kind: 'error',
          failure: {
            message: '无法检测新会话 id',
            code: 'SESSION_NOT_DETECTED',
          },
        },
      }
      return
    }

    let reply: string
    try {
      reply = await this.bridge.waitForReply(
        sessionId,
        wsState.lastReplyId,
        (signal ?? new AbortController().signal) as AbortSignal,
        {
          pollIntervalMs: this.config.pollIntervalMs ?? 3000,
          stableReadsRequired: this.config.stableReadsRequired ?? 4,
          timeoutMs: this.config.replyTimeoutMs ?? 240000,
        },
      )
    } catch (err) {
      yield {
        type: 'finish',
        reason: {
          kind: 'error',
          failure: {
            message: '取回复失败：' + String((err as Error)?.message ?? err),
            code: 'REPLY_WAIT_FAILED',
          },
        },
      }
      return
    }

    const parsed = this.parseReply(reply)
    let index = 0

    if (parsed.text) {
      yield { type: 'block-start', index, blockType: 'text' }
      yield { type: 'text-delta', index, text: parsed.text }
      yield {
        type: 'block-end',
        index,
        block: { type: 'text', text: parsed.text },
      }
      index++
    }

    for (const tc of parsed.toolCalls) {
      yield { type: 'block-start', index, blockType: 'tool-call' }
      yield {
        type: 'tool-call-delta',
        index,
        id: tc.id,
        name: tc.name,
        argumentsDelta: tc.arguments,
      }
      yield {
        type: 'block-end',
        index,
        block: {
          type: 'tool-call',
          id: tc.id,
          name: tc.name,
          arguments: tc.arguments,
        },
      }
      index++
    }

    yield {
      type: 'usage',
      usage: {
        inputTokens: Math.ceil(text.length / 4),
        outputTokens: Math.ceil(reply.length / 4),
      },
    }
    yield {
      type: 'finish',
      reason:
        parsed.toolCalls.length > 0
          ? { kind: 'tool-calls' }
          : { kind: 'stop' },
    }

    try {
      const lastMsg = options.messages[options.messages.length - 1] as any
      const newLastMessageId = lastMsg?.id ?? null
      const newSentCount = options.messages.length
      const newLastReplyId = await this.bridge.getLatestReplyId(sessionId)

      updateWorkspaceState(wsKey, {
        lastMessageId: newLastMessageId,
        sentCount: newSentCount,
        lastReplyId: newLastReplyId,
      })
      console.log(
        '[web-ds] 状态已保存：lastMessageId=' +
          newLastMessageId +
          ' sentCount=' +
          newSentCount +
          ' lastReplyId=' +
          newLastReplyId,
      )
    } catch (e) {
      console.error('[web-ds] 保存状态失败:', e)
    }
  }

  private deriveTitle(messages: readonly any[]): string {
    for (const m of messages) {
      if (m?.role !== 'user') continue
      const text = this.extractText(m)
      if (!text) continue
      if (isInternalText(text)) continue
      const trimmed = text.trim().replace(/\s+/g, ' ')
      if (!trimmed) continue
      return trimmed.length > 30 ? trimmed.slice(0, 30) + '…' : trimmed
    }
    return 'New Session'
  }

  private extractText(m: any): string {
    const content = m?.content
    if (typeof content === 'string') return content
    if (!Array.isArray(content)) return ''
    const out: string[] = []
    for (const b of content) {
      if (b && typeof b === 'object' && typeof b.text === 'string') {
        out.push(b.text)
      }
    }
    return out.join('\n')
  }

  private parseReply(reply: string): ParsedReply {
    const toolCalls: ParsedToolCall[] = []

    FENCED_BLOCK_RE.lastIndex = 0
    let m: RegExpExecArray | null
    while ((m = FENCED_BLOCK_RE.exec(reply)) !== null) {
      const tag = (m[1] || '').toLowerCase()
      const body = m[2] || ''
      try {
        const data = JSON.parse(body)
        this.collectCalls(data, toolCalls)
      } catch {
        // 不是合法 JSON，跳过
      }
    }

    FENCED_BLOCK_RE.lastIndex = 0
    const text = reply.replace(FENCED_BLOCK_RE, '').trim()
    return { text, toolCalls }
  }

  /** 把解析出来的 JSON 归一化成 tool-call 列表 */
  private collectCalls(data: any, out: ParsedToolCall[]): void {
    if (!data || typeof data !== 'object') return

    const push = (name: unknown, args: unknown) => {
      if (typeof name !== 'string' || !name) return
      const argsStr =
        typeof args === 'string' ? args : JSON.stringify(args ?? {})
      out.push({
        id: ('webds-' +
          Date.now() +
          '-' +
          out.length +
          '-' +
          Math.random().toString(36).slice(2, 6)) as unknown as ToolCallId,
        name,
        arguments: argsStr,
      })
    }

    // 直接是 {name, arguments}
    if (typeof data.name === 'string') {
      push(data.name, data.arguments)
      return
    }

    // 数组 [{name, arguments}, ...]
    if (Array.isArray(data)) {
      for (const item of data) {
        if (item && typeof item === 'object' && typeof item.name === 'string') {
          push(item.name, item.arguments)
        }
      }
      return
    }

    // {tool_calls: [...]}
    if (Array.isArray(data.tool_calls)) {
      for (const item of data.tool_calls) {
        if (item && typeof item === 'object' && typeof item.name === 'string') {
          push(item.name, item.arguments)
        }
      }
      return
    }

    // ds-agent 格式：{task: {steps: [{action, ...}]}}
    if (data.task && Array.isArray(data.task.steps)) {
      for (const step of data.task.steps) {
        if (!step || typeof step.action !== 'string') continue
        const args: Record<string, unknown> = {}
        for (const k of Object.keys(step)) {
          if (k !== 'action') args[k] = step[k]
        }
        push(step.action, args)
      }
      return
    }
  }
}